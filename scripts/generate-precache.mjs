/**
 * Emit dist/asset-precache.js after `vite build`.
 *
 * The service worker cannot know Vite's hashed asset names at source time, so
 * this post-build step lists every real shell file (JS, CSS, fonts, icons,
 * manifest and HTML) except the audio MP3s, which have their own generated
 * list. Skipping source maps keeps the offline payload small.
 */
import fs from 'node:fs';
import path from 'node:path';

const dist = path.resolve('dist');
const out = path.join(dist, 'asset-precache.js');
const skipDirs = new Set(['audio']);
const skipFiles = new Set(['sw.js', 'audio-precache.js', 'asset-precache.js']);

const urls = [];
function walk(dir, prefix) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = path.join(prefix, entry.name);
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (skipDirs.has(entry.name)) continue;
      walk(full, rel);
    } else if (!skipFiles.has(entry.name) && !entry.name.endsWith('.map')) {
      urls.push(`./${rel.split(path.sep).join('/')}`);
    }
  }
}
walk(dist, '');

urls.sort();
const body = [
  '/* Generated by scripts/generate-precache.mjs — do not edit by hand. */',
  `self.KANNADA_ASSET_PRECACHE = ${JSON.stringify(urls, null, 2)};`,
  '',
].join('\n');
fs.writeFileSync(out, body);
console.log(`asset-precache.js: ${urls.length} files`);
for (const url of urls) console.log(`  ${url}`);
